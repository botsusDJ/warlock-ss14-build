namespace Content.Server._Warlock.Artefacts.Components;

// _Warlock
// Реликвии трёх глав гильдий.
//
// Отличие реликвии от артефакта не в происхождении, а в масштабе. Обычный артефакт
// умеет одну вещь и берёт за неё свою цену. Реликвия умеет то, чего не умеет никто
// на станции, и цену берёт с гильдии, а не с носителя: пока глава жив и при реликвии,
// его гильдия работает иначе, чем остальные две.
//
// Поэтому все три сделаны практичными, а не эффектными. Кадило держит гильдию на ногах,
// Око снимает с находок лотерею, Сердце снимает вопрос заряда. Ни одна из трёх не бьёт:
// главам гильдий не нужно оружие, им нужно, чтобы гильдия работала.
//
// Реликвия одна на гильдию и выдаётся главе в стартовом снаряжении. Отнять её можно —
// на этом и держится их ценность как цели.

/// <summary>
/// _Warlock — «Кадило Касса». Реликвия Архимага-Епископа.
///
/// Зажжённое кадило раз в такт возвращает псионический резерв и гасит боль всем
/// членам гильдии вокруг. Это единственный на станции способ вернуть гильдии
/// возможность колдовать, не уходя с позиции.
///
/// Платит епископ, и платит собой: чем больше паствы в радиусе, тем быстрее он
/// сгорает. Кадило нельзя просто оставить включённым в углу — оно светит, шумит
/// и стоит епископу здоровья ровно за тех, кого обслуживает.
/// </summary>
[RegisterComponent]
public sealed partial class WarlockCenserComponent : Component
{
    /// <summary>Горит ли сейчас.</summary>
    [DataField]
    public bool Lit;

    /// <summary>Радиус воскурения в тайлах.</summary>
    [DataField]
    public float Range = 5f;

    /// <summary>Сколько резерва возвращается каждому за такт.</summary>
    [DataField]
    public float Energy = 9f;

    /// <summary>Сколько боли снимается каждому за такт.</summary>
    [DataField]
    public float Pain = 6f;

    /// <summary>Сколько удушья затягивается каждому за такт.</summary>
    [DataField]
    public float Airloss = 4f;

    /// <summary>
    /// Сколько клеточного урона епископ платит за каждого обслуженного, кроме себя.
    /// Клеточный выбран намеренно: он не лечится обычной медициной, и епископ,
    /// продержавший кадило весь раунд, доживает до конца развалиной.
    /// </summary>
    [DataField]
    public float CostPerHead = 0.7f;

    /// <summary>Раз в столько секунд считается воскурение.</summary>
    [DataField]
    public float TickInterval = 2f;

    [DataField]
    public TimeSpan NextTick;
}

/// <summary>
/// _Warlock — «Око Фактоса». Реликвия Артархимага.
///
/// Фактос ищет находки и гибнет на них: реликвия из пещеры может вылечить, а может
/// сломать кость тому, кто её поднял, и узнать это можно единственным способом.
/// Око отменяет этот способ. Артархимаг смотрит сквозь камень, видит весь его набор
/// и вырезает из него вредное — навсегда, для всех, кто возьмёт камень после.
///
/// Заряды конечны и не восстанавливаются. Это не инструмент на раунд, а решение
/// о том, какие четыре находки гильдия сделает безопасными.
/// </summary>
[RegisterComponent]
public sealed partial class WarlockSeersEyeComponent : Component
{
    /// <summary>
    /// Сколько находок Око способно приручить, прежде чем ослепнет.
    /// </summary>
    [DataField]
    public int Charges = 4;

    /// <summary>
    /// Сколько клеточного урона стоит Артархимагу одно приручение.
    /// Смотреть сквозь камень приходится своими глазами.
    /// </summary>
    [DataField]
    public float Cost = 12f;
}

/// <summary>
/// _Warlock — «Сердце Механтехиона». Реликвия Архитехномага.
///
/// Технос строит на батареях всё: рамы Братства, оружие, инструмент, свет в лагере.
/// Батарея — их главное узкое место, и Сердце его убирает: один разряд заряжает
/// досуха всё, что держит заряд, в радиусе.
///
/// Цена — ток через самого архитехномага. Разряд бьёт его самого, и тем сильнее,
/// чем больше он зарядил: полный лагерь техники обходится в реанимацию.
/// </summary>
[RegisterComponent]
public sealed partial class WarlockMachineHeartComponent : Component
{
    /// <summary>Радиус разряда в тайлах.</summary>
    [DataField]
    public float Range = 6f;

    /// <summary>
    /// Сколько урона током архитехномаг получает за каждую заряженную батарею.
    /// </summary>
    [DataField]
    public float ShockPerCell = 3.5f;

    /// <summary>
    /// Сколько структурного урона Сердце чинит машинам в радиусе заодно.
    /// </summary>
    [DataField]
    public float Repair = 25f;
}
