namespace Content.Shared._Warlock.Interaction;

/// <summary>
/// _Warlock
/// Насколько быстро существо делает то, что требует времени.
///
/// Поднимается на исполнителе в момент запуска любого DoAfter — единственной точке,
/// через которую в движке проходят все длительные взаимодействия сразу. Своего
/// механизма у ванили нет: длительность проставляется прямо на месте вызова, и без
/// этого события пришлось бы править сотни разных мест по отдельности.
///
/// Множитель именно множится, а не присваивается: источников может быть несколько
/// сразу — каста, травма, экзоскелет, — и каждый должен вносить свою долю, не затирая
/// чужую. Значение меньше единицы ускоряет, больше — замедляет.
/// </summary>
[ByRefEvent]
public record struct WarlockDoAfterSpeedEvent
{
    public float Multiplier = 1f;

    public WarlockDoAfterSpeedEvent()
    {
    }
}
