using Content.Shared.EntityEffects;

namespace Content.Shared._Warlock.Essence;

/// <summary>
/// _Warlock
/// Эффект метаболизма пси-эссенции: разгон сейчас, счётчик молча.
///
/// Пси-эссенция — это реагент, а не предмет. Она натекает лужей из-под мёртвого
/// скарабея, её можно зачерпнуть шприцем, разлить по склянкам, подмешать кому-нибудь
/// в стакан — и всё это работает само, потому что лужи и растворы в игре уже есть.
/// Раньше эссенция была сущностью со спрайтом лужи, которую пили щелчком по полу:
/// выглядело как жижа, вело себя как кнопка.
///
/// Лечение и урон делают ванильные эффекты в самом прототипе реагента. Здесь только
/// то, чего в ванили нет: разгон и необратимый счётчик выпитого.
/// </summary>
public sealed partial class WarlockEssenceDose : EntityEffectBase<WarlockEssenceDose>
{
    /// <summary>
    /// Сколько единиц эссенции засчитывается за один такт метаболизма.
    /// Должно совпадать с расходом реагента, иначе счёт разойдётся с выпитым.
    /// </summary>
    [DataField]
    public float Units = 0.5f;

    /// <summary>
    /// На сколько секунд такт продлевает разгон. Пока в крови есть эссенция,
    /// разгон не кончается — он кончается вместе с ней.
    /// </summary>
    [DataField]
    public float HighDuration = 12f;

    /// <summary>
    /// Сколько резерва возвращает единица эссенции.
    /// </summary>
    [DataField]
    public float EnergyPerUnit = 4f;
}
