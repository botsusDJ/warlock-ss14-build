using Robust.Shared.Serialization;

namespace Content.Shared._Warlock.Religion;

/// <summary>
/// _Warlock — божества, у которых в этой части галактики есть живые культы.
/// </summary>
[Serializable, NetSerializable]
public enum WarlockGod : byte
{
    /// <summary>
    /// Механтехион — бог-механизм Братства Стали. Требует исправности, презирает плоть и ксеносов.
    /// Молитва ему чинит машины и тех, кто сделан из металла.
    /// </summary>
    Mechantechion = 0,

    /// <summary>
    /// Касс — божество вымершей планетарной расы, создатель артефактов.
    /// Гильдия Варлок поклоняется ему напрямую; молитва возвращает псионическую энергию.
    /// </summary>
    Kass = 1,

    /// <summary>
    /// Дьёкт — бог изощрений, тактики, хитрости и гордости.
    /// Не даёт силы: даёт возможность уйти и вернуться на своих условиях.
    /// </summary>
    Djokt = 2,

    /// <summary>
    /// Атрак — бог ярости, честного боя, затяжных сражений, жестокости и крови.
    /// Не лечит и не прячет: вводит в ярость прямо здесь.
    /// </summary>
    Atrak = 3,

    /// <summary>
    /// Рузут — бог плодородия, обмана, похоти и жизни.
    /// Единственный, кто чинит тело: заживляет то, что вообще способно зажить.
    /// </summary>
    Ruzut = 4,
}
