using Robust.Shared.Serialization;

namespace Content.Shared._Warlock.Injuries;

/// <summary>
/// _Warlock — что тело помнит о полученном.
///
/// Это не вторая система здоровья: урон и смерть считает ваниль. Травмы — летопись,
/// которая копится поверх урона, читается в осмотре и немного мешает жить.
/// </summary>
[Serializable, NetSerializable]
public enum WarlockInjuryType : byte
{
    /// <summary>
    /// Ссадина. Копится от режущего и колющего, сходит быстро, ни на что не влияет.
    /// </summary>
    Abrasion = 0,

    /// <summary>
    /// Синяк. Копится от тупого урона, сходит медленно, режет запас выносливости.
    /// </summary>
    Bruise = 1,

    /// <summary>
    /// Перелом. Редкий и дорогой: замедляет, срастается долго и оставляет шрам.
    /// </summary>
    Fracture = 2,

    /// <summary>
    /// Шрам. Не сходит никогда. Остаётся от сросшихся переломов и глубоких ран.
    /// </summary>
    Scar = 3,

    /// <summary>
    /// Клеймо. Тоже навсегда, но ставится намеренно и означает принадлежность.
    /// </summary>
    Brand = 4,
}
