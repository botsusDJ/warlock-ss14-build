using Robust.Shared.GameStates;

namespace Content.Shared._Warlock.Guilds;

/// <summary>
/// _Warlock
/// Ранг в гильдии. Висит прямо на теле и выдаётся должностью при спавне.
///
/// Зачем компонент, а если должность и так лежит в разуме: проверка по разуму — это
/// цепочка из трёх звеньев (тело → контейнер разума → сущность роли → поле прототипа),
/// и достаточно порваться одному, чтобы архимаг оказался никем. Именно это и произошло
/// с гримуаром: командирский и капелланский разделы закрывались у того, кому они
/// принадлежат по должности.
///
/// Компонент на теле читается одним TryComp и не зависит ни от разума, ни от ролей,
/// ни от порядка их создания. Заодно ранг видно в ViewVariables и его можно выдать
/// админом, не выдавая должность целиком.
///
/// Ранг при этом остаётся честным: он приходит из должности через special в job-прототипе,
/// а не из одежды. Краденая мантия ранга не даёт.
/// </summary>
[RegisterComponent, NetworkedComponent, AutoGenerateComponentState]
public sealed partial class WarlockRankComponent : Component
{
    /// <summary>
    /// Ступень в иерархии, от 0 до 6.
    ///
    ///   0 — раб, вне иерархии
    ///   1 — адепт, послушник
    ///   2 — маг, брат
    ///   3 — ритуалист, зачарователь, техномансер
    ///   4 — жрец, чародей, техночародей
    ///   5 — верховный жрец, великий искатель, верховный технократ
    ///   6 — архимаг, артархимаг, архитехномаг
    /// </summary>
    [DataField, AutoNetworkedField]
    public int Rank;

    /// <summary>
    /// Духовенство. Отдельно от ранга, потому что иерархия и сан — разные лестницы:
    /// ритуалист третьей ступени служит, а зачарователь той же ступени — нет.
    /// </summary>
    [DataField, AutoNetworkedField]
    public bool Clergy;
}
